/* ============================================================
   Реестр мини-игр: каждая игра регистрирует себя здесь,
   оболочка (app.js) строит из этого домашний экран.
   ============================================================ */

const Games = {
  _list: [],

  register(id, def) {
    this._list.push(Object.assign({ id }, def));
  },

  get(id) {
    return this._list.find((g) => g.id === id);
  },
};
